export function locale(language) {
  return LOCALES[language] || "en";
}

/** A translator for one report language: t("key", {n: 3}). */
export function translator(language) {
  const table = STRINGS[locale(language)] || STRINGS.en;
  return (key, vars = {}) =>
    (table[key] ?? STRINGS.en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}
